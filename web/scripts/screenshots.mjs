// Regenerates the README images from demo mode (?demo): one per page, then the banner.
// Run through bin/screenshots. Uses the installed Google Chrome; no browser download.
import { spawn } from "node:child_process";
import { setTimeout as sleep } from "node:timers/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { writeFileSync, mkdirSync } from "node:fs";
import { chromium } from "playwright-core";
import { EXAMPLES } from "../themes/gallery/examples.ts";

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.resolve(here, "../../docs/images");
const port = Number(process.env.SCREENSHOT_PORT ?? 5199);
const base = `http://localhost:${port}/?demo`;
const pages = ["tasks", "glance", "news", "status"];

const vite = spawn("npx", ["vite", "--port", String(port), "--strictPort"], { cwd: path.resolve(here, ".."), stdio: "ignore" });
try {
  for (let i = 0; ; i++) {
    try { if ((await fetch(base)).ok) break; } catch { /* not up yet */ }
    if (i > 60) throw new Error(`vite did not start on port ${port}`);
    await sleep(250);
  }
  const browser = await chromium.launch({ channel: "chrome" });
  // The kiosk's panel is 1280x720; 2x keeps text crisp on retina screens.
  const context = await browser.newContext({ viewport: { width: 1280, height: 720 }, deviceScaleFactor: 2, colorScheme: "dark" });
  for (const id of pages) {
    const page = await context.newPage();
    await page.addInitScript((p) => localStorage.setItem("dashboard.page", p), id);
    await page.goto(base, { waitUntil: "networkidle" });
    await page.waitForTimeout(1500);
    await page.screenshot({ path: `${out}/${id}.png` });
    await page.close();
    console.log(`docs/images/${id}.png`);
  }
  // The widget gallery: one image per widget, then docs/widgets.md from the same examples.
  mkdirSync(`${out}/widgets`, { recursive: true });
  const gallery = await context.newPage();
  await gallery.goto(`${base}&theme=gallery`, { waitUntil: "networkidle" });
  await gallery.waitForTimeout(1200);
  for (const ex of EXAMPLES) {
    await gallery.locator(`#widget-${ex.name}`).screenshot({ path: `${out}/widgets/${ex.name}.png` });
  }
  // The echo example, after a little use: two messages and a few pongs.
  const echo = gallery.locator("#example-echo");
  for (const text of ["hello", "commands run in Lua"]) {
    await echo.getByRole("textbox").fill(text);
    await echo.getByRole("button", { name: "Echo" }).click();
    await gallery.waitForTimeout(250);
  }
  for (let i = 0; i < 3; i++) { await echo.getByRole("button", { name: "Ping" }).click(); await gallery.waitForTimeout(200); }
  await echo.screenshot({ path: `${out}/echo.png` });
  await gallery.close();
  writeFileSync(path.resolve(out, "../widgets.md"), widgetsDoc());
  console.log(`docs/images/widgets/*.png (${EXAMPLES.length}), docs/images/echo.png, docs/widgets.md`);

  const banner = await browser.newPage({ viewport: { width: 1280, height: 520 }, deviceScaleFactor: 2 });
  await banner.goto(`file://${out}/banner.html`, { waitUntil: "networkidle" });
  await banner.waitForTimeout(500);
  await banner.screenshot({ path: `${out}/banner.png` });
  console.log("docs/images/banner.png");
  await browser.close();
} finally {
  vite.kill();
}

function widgetsDoc() {
  const cell = (t) => t.replace(/\|/g, "\\|");
  const sections = EXAMPLES.map((ex) => [
    `## ui.${ex.name}`,
    "",
    ex.summary,
    "",
    `<img src="images/widgets/${ex.name}.png" alt="ui.${ex.name}" width="${Math.round((ex.width ?? 360) * 0.75)}">`,
    "",
    "```lua",
    ex.lua,
    "```",
    "",
    "| Option | |",
    "|---|---|",
    ...ex.options.map(([k, v]) => `| \`${k.split(", ").join("\`, \`")}\` | ${cell(v)} |`),
    "",
  ].join("\n"));
  return [
    "<!-- Generated by bin/screenshots from web/themes/gallery/examples.ts. Edit that file, not this one. -->",
    "",
    "# Widgets",
    "",
    "A module's `view(state, config)` returns a tree of these widgets, and the screen draws it inside",
    "the module's panel. Nothing here needs frontend code. When a widget doesn't fit, a module can ship",
    "its own React component instead: see [modules.md](modules.md).",
    "",
    "Open the dashboard with `?theme=gallery` to see every widget live.",
    "",
    "Widgets: " + EXAMPLES.map((ex) => `[${ex.name}](#ui${ex.name})`).join(" · "),
    "",
    ...sections,
  ].join("\n");
}
